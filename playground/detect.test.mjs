import assert from "node:assert/strict";
import test from "node:test";
import { detectFormats } from "./detect.mjs";

test("identifies all supported metadata formats without a filename", () => {
  for (const [text, expected] of [
    ["Package: lensgrind\nVersion: 1.0\n", "DESCRIPTION"],
    ['name="Lensgrind"\nuuid="00000000-0000-0000-0000-000000000001"', "Project.toml"],
    ["Metadata-Version: 2.6\nName: lensgrind\nVersion: 1.4.0\n", "METADATA"],
    ['[project]\nname="lensgrind"', "pyproject.toml"],
    ['[workspace.package]\nversion="1.0.0"', "Cargo.toml"],
    ["cff-version: 1.2.0\ntitle: lensgrind", "CITATION.cff"],
    [JSON.stringify({ "@context": "https://w3id.org/codemeta/3.0", name: "lensgrind" }), "codemeta.json"],
    [JSON.stringify({ title: "lensgrind", creators: [{ name: "Skłodowska-Curie, Marie" }] }), ".zenodo.json"],
    [JSON.stringify({ name: "lensgrind", author: "Marie Skłodowska-Curie" }), "package.json"],
    [JSON.stringify({ name: "@optics/lensgrind", license: "MIT" }), "package.json"],
    [JSON.stringify({ name: "optics/lensgrind", license: ["MIT", "Apache-2.0"] }), "composer.json"],
    ['<?xml version="1.0"?><project><modelVersion>4.0.0</modelVersion><name>Lensgrind</name></project>', "pom.xml"],
  ])
    assert.deepEqual(detectFormats(text), [expected]);
});

test("does not silently choose an ambiguous or unrecognised format", () => {
  assert.deepEqual(detectFormats('[project]\nname="one"\n[package]\nname="two"'), ["pyproject.toml", "Cargo.toml"]);
  assert.deepEqual(detectFormats('{"name":"unknown"}'), []);
  assert.deepEqual(detectFormats("not metadata"), []);
  assert.deepEqual(detectFormats("[]"), []);
  assert.deepEqual(detectFormats(""), []);
});

test("handles a BOM and gives CodeMeta precedence over generic npm fields", () => {
  assert.deepEqual(
    detectFormats(
      "\ufeff" +
        JSON.stringify({
          "@context": "https://w3id.org/codemeta/3.0",
          name: "lensgrind",
          version: "1.0.0",
          author: [],
        }),
    ),
    ["codemeta.json"],
  );
});

test("recognises the legacy CodeMeta DOI context and avoids guessing unknown JSON-LD as npm", () => {
  assert.deepEqual(
    detectFormats(
      JSON.stringify({
        "@context": "https://doi.org/10.5063/schema/codemeta-2.0",
        name: "lensgrind",
        version: "1.0.0",
        author: [],
      }),
    ),
    ["codemeta.json"],
  );
  assert.deepEqual(
    detectFormats(JSON.stringify({ "@context": "https://schema.org", name: "unknown", version: "1.0.0" })),
    [],
  );
});

test("detects a POM with tag whitespace or text resembling another metadata format", () => {
  assert.deepEqual(detectFormats("<project><modelVersion >4.0.0</modelVersion ></project>"), ["pom.xml"]);
  assert.deepEqual(
    detectFormats("<project><modelVersion>4.0.0</modelVersion><description>\n[project]\n</description></project>"),
    ["pom.xml"],
  );
});

test("detects a Maven POM whose namespace supplies the model version", () => {
  assert.deepEqual(
    detectFormats('<project xmlns="http://maven.apache.org/POM/4.1.0"><name>Lensgrind</name></project>'),
    ["pom.xml"],
  );
  assert.deepEqual(
    detectFormats(
      '<?xml version="1.0"?><m:project xmlns:m="http://maven.apache.org/POM/4.1.0"><m:name>Lensgrind</m:name></m:project>',
    ),
    ["pom.xml"],
  );
  assert.deepEqual(
    detectFormats(
      '<!-- POM generated by the build -->\n<?build hint?><project xmlns="http://maven.apache.org/POM/4.1.0"/>',
    ),
    ["pom.xml"],
  );
  assert.deepEqual(detectFormats("<!-- unfinished comment"), []);
  assert.deepEqual(detectFormats('<outer><project xmlns="http://maven.apache.org/POM/4.1.0"/></outer>'), []);
});
